// bundler.js
// Usage: node bundler.js <input.js> <output.bundle.js>
// Requires: npm install pako

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const zlib = require('zlib');
const { astCode } = require('./ast_code');

// Ensure pako present to inline into browser loader
const pakoPath = require.resolve('pako/dist/pako.min.js');

function b64(buf) { return Buffer.from(buf).toString('base64'); }
function fromB64(s) { return Buffer.from(s, 'base64'); }

function obfuscateKey(keyBuffer) {
    // XOR obfuscation with constant, then base64 encode
    const key = Buffer.from(keyBuffer);
    const out = Buffer.alloc(key.length);
    const XOR = 0xA5;
    for (let i = 0; i < key.length; i++) out[i] = key[i] ^ XOR;
    // further scramble by splitting into chunks
    const parts = [];
    const chunk = 6;
    for (let i = 0; i < out.length; i += chunk) {
        parts.push(out.slice(i, i + chunk).toString('base64'));
    }
    return { parts, xor: XOR };
}

function deobfuscationSnippet(partsVarName, xorVal) {
    // returns JS snippet to reconstruct key Uint8Array at runtime
    // partsVarName should be an identifier that holds array of base64 parts
    return `
    (function(){
      const _parts = ${partsVarName};
      let _chunks = [];
      for (let i=0;i<_parts.length;i++){
        const _b = (typeof Buffer !== 'undefined') ? Buffer.from(_parts[i], 'base64') : (function(){ 
          // browser base64->Uint8Array
          const s = atob(_parts[i]);
          const u = new Uint8Array(s.length);
          for (let j=0;j<s.length;j++) u[j]=s.charCodeAt(j);
          return u;
        })();
        _chunks.push(_b);
      }
      // concat
      let _len = 0; for (let i=0;i<_chunks.length;i++) _len += _chunks[i].length;
      const _buf = (typeof Buffer !== 'undefined') ? Buffer.alloc(_len) : new Uint8Array(_len);
      let _off = 0;
      for (let i=0;i<_chunks.length;i++){
        const c = _chunks[i];
        for (let j=0;j<c.length;j++){
          _buf[_off++] = c[j];
        }
      }
      // XOR back
      const XOR = ${xorVal};
      for (let i=0;i<_buf.length;i++) _buf[i] = _buf[i] ^ XOR;
      return _buf;
    })()
  `;
}

// build
(async function main() {
    const argv = process.argv.slice(2);
    if (argv.length < 2) {
        console.error('Usage: node bundler.js <input.js> <output.bundle.js>');
        process.exit(2);
    }
    const [inputFile, outputFile] = argv;

    const src = fs.readFileSync(path.resolve(inputFile), 'utf8');

    // compress
    const compressed = zlib.deflateSync(Buffer.from(src, 'utf8'));

    // generate random AES-256-GCM key & iv
    const key = crypto.randomBytes(32); // 256-bit
    const iv = crypto.randomBytes(12); // recommended 12 bytes for GCM

    // encrypt
    const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
    const ciphertext = Buffer.concat([cipher.update(compressed), cipher.final()]);
    const authTag = cipher.getAuthTag();

    // sha256 of plaintext (for extra verification after decryption)
    const sha = crypto.createHash('sha256').update(compressed).digest();

    // obfuscate key
    const { parts, xor } = obfuscateKey(key);

    // read pako to inline into browser runtime
    const pakoCode = fs.readFileSync(pakoPath, 'utf8');

    // prepare payload pieces (base64)
    const payload = {
        ciphertext: b64(ciphertext),
        iv: b64(iv),
        tag: b64(authTag),
        sha256: b64(sha),
        keyParts: parts,
        xor
    };

    // runtime loader template (obfuscated a bit)
    let runtime = `
/* bundle loader generated by custom bundler */
(function(){
  // === embedded pako for browser decompression ===
  var __INLINE_PAKO = (function(){
    // pako is inlined below only for browsers. Node will use zlib.
    __PAKO_CODE_PLACEHOLDER__
    return typeof pako !== 'undefined' ? pako : null;
  })();

  // base64 helpers
  function _b64ToBytesNode(s){ return (typeof Buffer !== 'undefined') ? Buffer.from(s, 'base64') : null; }
  function _b64ToUint8(s){
    if (typeof Buffer !== 'undefined') {
      return Buffer.from(s, 'base64');
    } else {
      const bin = atob(s);
      const out = new Uint8Array(bin.length);
      for (let i=0;i<bin.length;i++) out[i] = bin.charCodeAt(i);
      return out;
    }
  }

  // reconstruct key (obfuscated parts)
  const _KEY_PARTS = ${JSON.stringify(payload.keyParts)};
  const _RECON_KEY_BUF = ${deobfuscationSnippet('_KEY_PARTS', payload.xor)};

  const _CIPHER_B64 = "${payload.ciphertext}";
  const _IV_B64 = "${payload.iv}";
  const _TAG_B64 = "${payload.tag}";
  const _SHA256_B64 = "${payload.sha256}";

  // environment helpers
  const _isNode = (typeof process !== 'undefined' && process.versions && process.versions.node);
  function _toUint8Array(bufLike){
    if (typeof Buffer !== 'undefined' && Buffer.isBuffer(bufLike)) return new Uint8Array(bufLike);
    if (bufLike instanceof Uint8Array) return bufLike;
    return new Uint8Array(bufLike);
  }

  async function _decryptAndRun(){
    try {
      const cipherBytes = _b64ToUint8(_CIPHER_B64);
      const iv = _b64ToUint8(_IV_B64);
      const tag = _b64ToUint8(_TAG_B64);
      const keyBuf = _RECON_KEY_BUF;

      let plainCompressed;
      // Node path
      if (_isNode) {
        const crypto = require('crypto');
        const decipher = crypto.createDecipheriv('aes-256-gcm', keyBuf, Buffer.from(iv));
        decipher.setAuthTag(Buffer.from(tag));
        const dec = Buffer.concat([decipher.update(Buffer.from(cipherBytes)), decipher.final()]);
        plainCompressed = dec;
        // verify sha256
        const expected = Buffer.from("${payload.sha256}", 'base64');
        const actual = crypto.createHash('sha256').update(plainCompressed).digest();
        if (!expected.equals(actual)) for (;;) {};
        // decompress using zlib
        const zlib = require('zlib');
        const plainBuf = zlib.inflateSync(plainCompressed);
        const src = plainBuf.toString('utf8');
        // execute
        (new Function(src))();
        return;
      }

      // Browser path: use Web Crypto + pako
      // import key
      const subtle = (typeof crypto !== 'undefined' && crypto.subtle) ? crypto.subtle : null;
      if (!subtle) for (;;) {};

      // import AES-GCM key
      const cryptoKey = await subtle.importKey('raw', _toUint8Array(keyBuf), 'AES-GCM', false, ['decrypt']);

      // decrypt
            // WebCrypto expects ciphertext || tag concatenated. Append tag to ciphertext.
      const ct = _toUint8Array(cipherBytes);
      const tg = _toUint8Array(tag);
      const combined = new Uint8Array(ct.length + tg.length);
      combined.set(ct, 0);
      combined.set(tg, ct.length);

      const alg = { "name": 'AES-GCM', "iv": _toUint8Array(iv), "tagLength": 128 };
      const plainArrayBuffer = await subtle.decrypt(alg, cryptoKey, combined.buffer);


      // verify SHA256 of compressed plaintext
      const expected = Uint8Array.from(atob("${payload.sha256}"), c => c.charCodeAt(0));
      // compute SHA-256 via subtle
      const gotHashBuf = await subtle.digest('SHA-256', plainArrayBuffer);
      const gotHash = new Uint8Array(gotHashBuf);
      // compare
      let ok = true;
      if (gotHash.length !== expected.length) ok = false;
      else {
        for (let i=0;i<gotHash.length;i++) if (gotHash[i] !== expected[i]) { ok = false; break; }
      }
      if (!ok) for (;;) {};

      // decompress using pako
      if (!__INLINE_PAKO) for (;;) {};
      const compressedUint8 = new Uint8Array(plainArrayBuffer);
      const src = __INLINE_PAKO.inflate(compressedUint8, { to: 'string' });

      // execute
      (new Function(src))();
    } catch (e) {
      if (typeof console !== 'undefined') {
        try { for (;;) {}; } catch(_) {}
      }
    }
  }

  // Kick off loader (async)
  // we create an async IIFE to avoid top-level await requirement
  (function(){ _decryptAndRun(); })();

})();
`;

    runtime = astCode(runtime).code;
    runtime = runtime.replace("__PAKO_CODE_PLACEHOLDER__", pakoCode)

    fs.mkdirSync(path.dirname(outputFile), { recursive: true });
    fs.writeFileSync(outputFile, runtime, 'utf8');

    console.log('Bundle written to', outputFile);
    console.log('  - AES-256-GCM key (obfuscated inside bundle).');
    console.log('  - You can run the bundle in Node: node', outputFile);
    console.log('  - Or include <script src="bundle.js"></script> in a browser (pako inlined).');
})();